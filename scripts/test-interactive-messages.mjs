import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context = { console, URL, setTimeout, clearTimeout };
context.window = context;
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('../js/modules/interactive-messages.js', import.meta.url), 'utf8'), context);
vm.runInContext(fs.readFileSync(new URL('../js/core/ui-and-content-utils.js', import.meta.url), 'utf8'), context);
const api = context.InteractiveMessages;
const page = '<!DOCTYPE html><html lang="zh"><head><title>图集</title></head><body><script>const x = "<html>";const y="[角色的转账：1元]";if(1<2){console.log("中文\\\"<>&")}</script><button onclick="this.textContent=\'成功\'">切换</button></body></html>';
assert.equal(api.extract('讨论 <script> 的用法'), null);
assert.equal(api.extract('<div>旧卡片</div>'), null);
assert.equal(api.extract(page).source, page);
assert.equal(api.extract('```html\n' + page + '\n```').source, page);
assert.equal(api.extract('<uwuxjc>' + page + '</uwuxjc>').source, page);
assert.equal(api.extract('<div>片段</div>', true).source, '<div>片段</div>');
const mixed = '[角色的消息：看看这个]<uwuxjc char="角色">' + page + '</uwuxjc>[角色的消息：喜欢吗]';
const parts = context.getMixedContent(mixed);
assert.equal(parts.length, 3);
assert.equal(parts[1].type, 'html');
assert.equal(parts[1].char, '角色');
assert.equal(parts[1].content, '<uwuxjc char="角色">' + page + '</uwuxjc>');
const two = '<uwuxjc><p>A</p></uwuxjc><uwuxjc><p>B</p></uwuxjc>';
assert.equal(api.extract(two), null);
assert.equal(context.getMixedContent(two).length, 2);
assert.equal(context.getMixedContent(page)[0].content, page);
const protectedResponse = api.protectResponse('[角色的消息：前]' + two + page + '[角色的消息：后]');
assert.ok(!protectedResponse.text.includes('<script>'));
assert.equal(protectedResponse.restore(protectedResponse.text), '[角色的消息：前]' + two + page + '[角色的消息：后]');
const text = { content: page, parts: [{ type: 'text', text: page }] };
assert.equal(api.sourceOf(text), null, 'ordinary text is not executed by the renderer');
const legacy = { content: '<div>旧卡片</div>', parts: [{ type: 'html', text: '<div>旧卡片</div>' }] };
assert.equal(api.sourceOf(legacy), null, 'legacy fragment stays on the sanitized rendering path');
assert.equal(api.apply(text, page), true);
assert.equal(api.sourceOf(text).source, page);
text.interactive.state = { index: 3 };
api.apply(text, page);
assert.equal(text.interactive.state.index, 3);
assert.equal(api.contextText(text), '[互动页面：图集]');
text.interactive.summary = '选了第三张';
assert.ok(api.contextText(text).includes('选了第三张'));
assert.ok(!api.contextText(text).includes('<script>'));
const chat = { id: 'a', history: [text] };
const filtered = context.filterHistoryForAI(chat);
assert.ok(!filtered[0].content.includes('<script>'));
assert.equal(text.parts[0].text, page, 'context serialization never modifies source');
assert.equal(api.apply(text, page, 'text'), false);
assert.equal(api.sourceOf(text), null);
assert.throws(() => api.apply({}, '<uwuxjc>' + 'x'.repeat(512 * 1024 + 1) + '</uwuxjc>'), /512/);
assert.deepEqual(Array.from(api.allowedOrigins('https://cdn.example.com/lib.js https://cdn.example.com')), ['https://cdn.example.com']);
assert.throws(() => api.allowedOrigins("https://ok.example 'unsafe-eval'"), /HTTPS/);
assert.throws(() => api.allowedOrigins('http://example.com'), /HTTPS/);
assert.throws(() => api.allowedOrigins('https://user:password@example.com'), /HTTPS/);
assert.equal(api.template({format:'ovo-html-template',source:page}).state.constructor.name, 'Object');
assert.throws(() => api.template({format:'ovo-html-template',source:page,state:[]}), /进度/);
vm.runInContext(fs.readFileSync(new URL('../js/modules/chat-ai/response-and-control.js', import.meta.url), 'utf8'), context);
context.db = { characters: [chat], groups: [] };
chat.history = [];
context.executePhoneControlCommands = text => {
    assert.ok(!text.includes('<script>'), 'global commands never inspect page source');
    return { executed: false, cleaned: text };
};
context.addMessageBubble = () => {};
context.renderChatList = () => {};
context.saveCharacter = async () => true;
await context.handleAiReplyContent(page, chat, 'a', 'private', true, false, { suppressAutoTasks: true });
assert.equal(chat.history.length, 1);
assert.equal(chat.history[0].parts[0].text, page);
assert.equal(chat.history[0].interactive.enabled, true);
vm.runInContext(fs.readFileSync(new URL('../js/modules/chat-render/message-actions.js', import.meta.url), 'utf8'), context);
context.document = { getElementById: () => null };
context.currentChatId = 'other'; context.currentChatType = 'private';
context.showToast = () => {};
context.db.globalToastEnabled = false;
let walletCalls = 0;
context.WalletSystem = { processFamilyCardActionMessage: () => { walletCalls++; } };
const interactiveMessage = chat.history[0];
context.addMessageBubble(interactiveMessage, 'a', 'private');
assert.equal(walletCalls, 0, 'page source cannot trigger business commands during message delivery');
assert.equal(chat.unreadCount, 1, 'background interactive messages still count as unread');
assert.equal(interactiveMessage.content, page, 'delivery view leaves original source intact');
console.log('Interactive message recognition, mixed parsing, legacy compatibility, state and AI context checks passed.');
